'use strict'
const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { Repository } = require('../desktop/database.cjs')
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tangtang-requirements-db-'))
const dbPath = path.join(dir, 'test.sqlite')
let repo
try {
  repo = new Repository(dbPath)
  const create = (orderId, orderForm = {}) => repo.createOrder({ orderId, orderForm, sizeList: [{ sizeNote: 'ONLY-LINE', singlePrice: 123 }], totalPrice: 987 })
  create('20261117999')
  create('202611171000')
  assert.deepEqual(repo.nextOrderNumber({ date: '20261117', index: '999' }), { no: '202611171001', index: '1001' })
  assert.deepEqual(repo.nextOrderNumber({ date: '20261117', index: '999' }), { no: '202611171001', index: '1001' }, 'Suggesting alone does not reserve or increment')
  assert.deepEqual(repo.nextOrderNumber({ date: '20261118', index: '1001' }), { no: '202611181001', index: '1001' }, 'Next day retains the session index supplied by the caller')
  create('UNICODE', { clientName: 'Straße', dealerName: '测试经销商', call: '01234567890', clientAddress: '100%_real', no: 'UNICODE', custom: 123 })
  create('BOUNDARY', { clientName: 'AB', clientAddress: 'CD' })
  for (const term of ['STRASSE', 'straße', '测试', '0123', '100%_', '123'])
    assert.equal(repo.listOrders({ search: term }).total, 1, term)
  assert.equal(repo.listOrders({ search: 'BC' }).total, 0, 'Do not match across fields')
  assert.equal(repo.listOrders({ search: 'ONLY-LINE' }).total, 0)
  repo.saveOrderDetail({ orderId: 'UNICODE', detailForm: { receiveName: 'ONLY-DETAIL', yingPay: '10', amountPay: '999' } })
  assert.equal(repo.listOrders({ search: 'ONLY-DETAIL' }).total, 0)
  assert.equal(repo.getOrderHeader('UNICODE').totalPrice, 987, 'Never recompute existing totals from line prices or payment fields')
  assert.equal(repo.getOrderHeader('BOUNDARY').detailForm, undefined, 'Missing historical detail remains missing')
  for (let i = 0; i < 105; i++) create('MATCH' + String(i).padStart(3, '0'), { clientName: '限定客户' })
  const second = repo.listOrders({ search: '限定客户', page: 2 })
  assert.equal(second.total, 105)
  assert.deepEqual(second.items.map((item) => item.orderId), ['MATCH004', 'MATCH003', 'MATCH002', 'MATCH001', 'MATCH000'])
  assert.equal(second.items[0].sizeList, undefined)
  const header = repo.getOrderHeader('UNICODE')
  const lines = repo.listOrderItems({ orderId: 'UNICODE' })
  const settings = repo.getSettings()
  settings.baseForm.doorWidthDiff = 200
  repo.saveSettings(settings)
  assert.deepEqual(repo.getOrderHeader('UNICODE'), header)
  assert.deepEqual(repo.listOrderItems({ orderId: 'UNICODE' }), lines)
  repo.close()
  repo = new Repository(dbPath)
  assert.equal(repo.getSettings().baseForm.doorWidthDiff, 200)
  assert.equal(repo.getOrderHeader('UNICODE').detailForm.amountPay, '999')
  console.log('requirements-storage: numbering rollover/session index, Unicode/literal/field-only search, filtered pagination, independent payments and immutable snapshots passed')
} finally {
  repo?.close()
  fs.rmSync(dir, { recursive: true, force: true })
}
