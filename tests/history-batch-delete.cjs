const { _electron: electron, expect } = require('@playwright/test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const { spawnSync } = require('node:child_process')
const root = path.resolve(__dirname, '..')
const data = fs.mkdtempSync(path.join(os.tmpdir(), 'tangtang-history-batch-'))
const env = { ...process.env, TANGTANG_DATA_DIR: data }
delete env.ELECTRON_RUN_AS_NODE
delete env.TANGTANG_DEV_URL
const seed = spawnSync(require('electron'), [path.join(__dirname, 'seed.cjs'), data], {
  env: { ...env, ELECTRON_RUN_AS_NODE: '1' }, encoding: 'utf8',
})
assert.equal(seed.status, 0, seed.stderr)
let app
function runSql(sql) {
  const result = spawnSync(require('electron'), [
    '-e', 'const {Repository}=require(process.argv[1]);const repo=new Repository(process.argv[2]);try{repo.db.exec(process.argv[3])}finally{repo.close()}',
    path.join(root, 'desktop', 'database.cjs'), path.join(data, 'development-db', 'tangtang.sqlite'), sql,
  ], { env: { ...env, ELECTRON_RUN_AS_NODE: '1' }, encoding: 'utf8' })
  assert.equal(result.status, 0, result.stderr)
}
async function setChecked(checkbox, checked) {
  // Element Plus hides the native input; users click its visible label.
  if ((await checkbox.isChecked()) !== checked)
    await checkbox.locator('xpath=ancestor::label').click()
  await expect(checkbox).toBeChecked({ checked })
}
async function main() {
  app = await electron.launch({ args: [root], cwd: root, env })
  const page = await app.firstWindow()
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.getByRole('button', { name: '历史记录', exact: false }).click()
  const list = page.locator('.history-list')
  const checks = list.getByRole('checkbox', { name: /^选择订单 / })
  const all = list.getByRole('checkbox', { name: '全选本页', exact: true })
  const remove = list.getByRole('button', { name: /^批量删除/ })
  await expect(page.locator('.summary-item')).toHaveCount(100)
  await expect(checks).toHaveCount(100)
  await expect(remove).toBeDisabled()
  await expect(page.locator('.history-detail .document-number')).toContainText('20261115202')
  await setChecked(checks.nth(0), true)
  await setChecked(checks.nth(1), true)
  await expect(remove).toHaveText('批量删除（2）')
  // Checking a row must not navigate away from the currently displayed document.
  await expect(page.locator('.history-detail .document-number')).toContainText('20261115202')
  await remove.click()
  const dialog = page.getByRole('dialog', { name: '批量删除订单', exact: true })
  await expect(dialog).toContainText('2 笔订单')
  await expect(dialog).toContainText('删除后无法恢复')
  assert.equal((await page.evaluate(() => window.tangtang.listOrders())).total, 202)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(remove).toHaveText('批量删除（2）')
  assert.equal((await page.evaluate(() => window.tangtang.listOrders())).total, 202)
  runSql("CREATE TRIGGER fail_batch BEFORE DELETE ON orders WHEN OLD.order_id='20261115201' BEGIN SELECT RAISE(ABORT, 'batch delete test failure'); END")
  await remove.click()
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByText('batch delete test failure', { exact: true })).toBeVisible()
  await expect(remove).toBeEnabled()
  await expect(remove).toHaveText('批量删除（2）')
  assert.equal((await page.evaluate(() => window.tangtang.listOrders())).total, 202)
  assert.ok(await page.evaluate(() => window.tangtang.getOrderHeader('20261115202')))
  runSql('DROP TRIGGER fail_batch')
  await setChecked(all, true)
  await expect(remove).toHaveText('批量删除（100）')
  await setChecked(checks.nth(0), false)
  await expect(remove).toHaveText('批量删除（99）')
  await expect(all).not.toBeChecked()
  await setChecked(all, true)
  await setChecked(all, false)
  await expect(remove).toBeDisabled()
  await setChecked(checks.nth(0), true)
  await list.locator('.el-pager li').filter({ hasText: /^3$/ }).click()
  await expect(page.locator('.summary-item')).toHaveCount(2)
  await expect(remove).toBeDisabled()
  await setChecked(all, true)
  await remove.click()
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.locator('.summary-item')).toHaveCount(100)
  await expect(list.locator('.el-pager .is-active')).toHaveText('2')
  await expect(remove).toBeDisabled()
  assert.equal((await page.evaluate(() => window.tangtang.listOrders())).total, 200)
  assert.equal(await page.evaluate(() => window.tangtang.getOrderHeader('20261115001')), null)
  assert.equal(await page.evaluate(() => window.tangtang.getOrderHeader('20261115002')), null)
  assert.ok(await page.evaluate(() => window.tangtang.getOrderHeader('20261115202')))
  await setChecked(checks.nth(0), true)
  await page.getByLabel('搜索订单').fill('客户202')
  await expect(page.locator('.summary-item')).toHaveCount(1)
  await expect(remove).toBeDisabled()
  await setChecked(all, true)
  await remove.click()
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByText('没有匹配的订单', { exact: true })).toBeVisible()
  await expect(page.locator('.history-detail .document-number')).toHaveCount(0)
  await expect(all).toBeDisabled()
  assert.equal((await page.evaluate(() => window.tangtang.listOrders())).total, 199)
  await page.getByLabel('搜索订单').fill('')
  await expect(page.locator('.summary-item')).toHaveCount(100)
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1024, 600))
  await expect(remove).toBeVisible()
  await expect(list.locator('.el-loading-mask')).toHaveCount(0)
  await expect(page.locator('.el-message')).toHaveCount(0)
  const bounds = await page.locator('.history-page').evaluate((el) => ({ height: el.clientHeight, content: el.scrollHeight }))
  assert.ok(bounds.content <= bounds.height + 1, JSON.stringify(bounds))
  fs.mkdirSync(path.join(root, 'test-results'), { recursive: true })
  await page.screenshot({ path: path.join(root, 'test-results', 'history-batch-delete.png') })
  assert.deepEqual(errors, [])
  await app.close()
  app = await electron.launch({ args: [root], cwd: root, env })
  const reopened = await app.firstWindow()
  await reopened.locator('.calculator-content .input-panel h2').waitFor()
  assert.equal((await reopened.evaluate(() => window.tangtang.listOrders())).total, 199)
  console.log('history-batch-delete: selection, cancellation, failure recovery, page/search reset, deletion, page fallback, empty detail, small window and restart passed')
}
main().catch((error) => { console.error(error); process.exitCode = 1 }).finally(async () => {
  if (app) await app.close()
  fs.rmSync(data, { recursive: true, force: true })
})
