'use strict'
const assert = require('assert/strict')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { Repository } = require('../desktop/database.cjs')
const { migrate } = require('../desktop/migrate.cjs')
async function main() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tangtang-storage-'))
  let repo
  try {
    repo = new Repository(path.join(dir, 'test.sqlite'))
    assert.deepEqual(repo.getSettings().texturesOptions, [])
    const original = { orderId: '20261116001', orderForm: { clientName: 'Abc', address: 'Def', contact: 123,deliveryDate:new Date('2026-11-16T00:00:00Z') }, sizeList: [{ singlePrice: 0.1,customDate:new Date(5) }, { singlePrice: 0.2 }], totalPrice: 0.30000000000000004, legacy: { untouched: true } }
    repo.createOrder(original)
    original.sizeList[0].singlePrice = 900
    assert.equal(repo.listOrderItems({orderId: original.orderId}).items[0].singlePrice, 0.1)
    assert.equal(repo.listOrderItems({orderId: original.orderId}).items[0].customDate.getTime(), 5)
    assert.equal(repo.listOrders({search:original.orderForm.deliveryDate.toString()}).total,1)
    assert.equal(repo.db.pragma('user_version',{simple:true}),2)
    assert.equal(repo.db.pragma('journal_mode',{simple:true}),'wal')
    assert.equal(repo.db.pragma('synchronous',{simple:true}),2)
    assert.equal(repo.getOrderHeader(original.orderId).sizeList, undefined)
    assert.deepEqual(repo.getOrderHeader(original.orderId).legacy, {untouched: true})
    assert.equal(repo.listOrders({search:'cD'}).total, 0)
    assert.equal(repo.listOrders({search:'bc'}).total, 1)
    assert.equal(repo.listOrders({search:'23'}).total, 1)
    assert.equal(repo.listOrders({search:'singlePrice'}).total, 0)
    assert.equal(repo.listOrders({search:'%'}).total, 0)
    assert.equal(repo.listOrders({search:'_'}).total, 0)
    assert.throws(() => repo.createOrder({...original, sizeList:[{}]}))
    assert.equal(repo.listOrderItems({orderId:original.orderId}).total, 2)
    assert.throws(()=>repo.createOrder({orderId:'broken-insert',orderForm:{},sizeList:[{},undefined]}))
    assert.equal(repo.getOrderHeader('broken-insert'),null)
    const cyclic={};cyclic.self=cyclic
    assert.throws(()=>repo.createOrder({orderId:'rollback-after-header',orderForm:{},sizeList:[{},cyclic]}))
    assert.equal(repo.getOrderHeader('rollback-after-header'),null)
    for(const invalid of [null,[],0,'row',new Date(0)]) {
      assert.throws(()=>repo.createOrder({orderId:'invalid-row',orderForm:{},sizeList:[invalid]}))
      assert.equal(repo.getOrderHeader('invalid-row'),null)
      assert.throws(()=>repo.createOrder({orderId:'invalid-form',orderForm:invalid,sizeList:[]}))
      assert.throws(()=>repo.saveOrderDetail({orderId:original.orderId,detailForm:invalid}))
    }
    assert.throws(()=>repo.createOrder({orderId:'invalid-detail',orderForm:{},sizeList:[],detailForm:null}))
    for(let i=0;i<125;i++) repo.createOrder({orderId:'X'+String(i).padStart(3,'0'),orderForm:{clientName:'客户'},sizeList:[],totalPrice:0})
    assert.equal(repo.listOrders({pageSize:999}).items.length, 100)
    assert.equal(repo.listOrders({page:2,pageSize:100}).items.length, 26)
    assert.equal(repo.listOrders({}).items[0].orderId, 'X124')
    const permissive={orderId:'legacy-values',orderForm:{clientName:'',contact:0,custom:null},sizeList:[{price:'',number:-1,singlePrice:0,unknown:{old:true}}],detailForm:{amountPay:'',unknown:null},totalPrice:0}
    repo.createOrder(permissive)
    assert.deepEqual(repo.listOrderItems({orderId:permissive.orderId}).items,permissive.sizeList)
    repo.deleteOrder(permissive.orderId)
    assert.deepEqual(repo.nextOrderNumber({date:'20261116',index:'001'}),{no:'20261116002',index:'002'})
    assert.deepEqual(repo.nextOrderNumber({date:'20261117',index:'999'}),{no:'20261117999',index:'999'})
    repo.saveCalculation({_id:'case-one', createDate:1, old:true})
    repo.saveSettings({version:1,baseForm:{x:2},inactive:'kept'})
    repo.saveSettings({version:1,colorOptions:[]})
    assert.equal(repo.getSettings().inactive,'kept')
    const validSetting=repo.getSettings()
    for(const invalid of [{baseForm:null},{baseForm:[]},{typeOptions:[null]},{colorOptions:'red'},{texturesOptions:[1]}]) {
      assert.throws(()=>repo.saveSettings({version:1,...invalid}))
      assert.deepEqual(repo.getSettings(),validSetting)
    }
    repo.createOrder({orderId:'BIG',orderForm:{clientName:'large'},sizeList:Array.from({length:601},(_,i)=>({position:i})),totalPrice:0})
    assert.equal(repo.listOrderItems({orderId:'BIG',limit:10000}).items.length,500)
    assert.equal(repo.listOrderItems({orderId:'BIG',offset:600,limit:100}).items[0].position,600)
    const reader=new Repository(path.join(dir,'test.sqlite'),{readonly:true})
    assert.equal(reader.getOrderHeader('BIG').itemCount,601)
    assert.throws(()=>reader.deleteOrder('BIG'))
    reader.close()
    repo.saveOrderDetail({orderId:original.orderId,detailForm:{receiveName:'A'}})
    assert.equal(repo.getOrderHeader(original.orderId).detailForm.receiveName,'A')
    repo.deleteOrder(original.orderId)
    assert.equal(repo.db.prepare('SELECT count(*) n FROM calculations').get().n,1)
    assert.equal(repo.listOrderItems({orderId:original.orderId}).total,0)
    repo.db.pragma('user_version=0')
    repo.close(); repo=null
    repo=new Repository(path.join(dir,'test.sqlite'))
    assert.equal(repo.getOrderHeader('BIG').itemCount,601)
    assert.equal(fs.readdirSync(dir).filter(name=>name.startsWith('test.sqlite.before-schema-2-')).length,1)
    repo.db.pragma('user_version=999');repo.close();repo=null
    assert.throws(()=>new Repository(path.join(dir,'test.sqlite')),/更高版本/)
    const legacy=path.join(dir,'legacy'); fs.mkdirSync(legacy)
    fs.writeFileSync(path.join(legacy,'order.db'), [JSON.stringify({_id:'a',orderId:'old',orderForm:{name:'first'},sizeList:[{x:1}],totalPrice:1}),JSON.stringify({_id:'a',orderId:'old',orderForm:{name:'new',deliveryDate:{$$date:10}},sizeList:[{x:2}],totalPrice:2,date:{$$date:10}}),JSON.stringify({_id:'gone',orderId:'gone'}),JSON.stringify({_id:'gone',$$deleted:true}),JSON.stringify({$$indexCreated:{fieldName:'orderId',unique:true}})].join('\n'))
    fs.writeFileSync(path.join(legacy,'case.db'),JSON.stringify({_id:'c',createDate:{$$date:5}}))
    fs.writeFileSync(path.join(legacy,'setting.db'),JSON.stringify({_id:'s',version:1,baseForm:{old:1},inactive:99}))
    const result=await migrate({sourceDir:legacy,destinationPath:path.join(dir,'migrated.sqlite')})
    assert.equal(result.counts.order,1)
    assert.deepEqual(fs.readFileSync(path.join(result.backupDir,'order.db')),fs.readFileSync(path.join(legacy,'order.db')))
    for(const pair of Object.values(result.hashes))assert.equal(pair.source,pair.destination)
    await assert.rejects(migrate({sourceDir:legacy,destinationPath:path.join(dir,'migrated.sqlite')}))
    repo=new Repository(path.join(dir,'migrated.sqlite'))
    assert.equal(repo.getOrderHeader('old').orderForm.name,'new')
    assert.equal(repo.getOrderHeader('old').date.getTime(),10)
    assert.equal(repo.listOrders({search:new Date(10).toString()}).total,1)
    assert.equal(repo.listOrderItems({orderId:'old'}).items[0].x,2)
    assert.equal(repo.getSettings().inactive,99)
    repo.close();repo=null
    fs.appendFileSync(path.join(legacy,'order.db'),'\n{broken')
    await assert.rejects(migrate({sourceDir:legacy,destinationPath:path.join(dir,'bad.sqlite')}))
    assert.equal(fs.existsSync(path.join(dir,'bad.sqlite')),false)
    fs.writeFileSync(path.join(legacy,'order.db'),JSON.stringify({_id:'a',orderId:'duplicate',orderForm:{},sizeList:[]})+'\n'+JSON.stringify({_id:'b',orderId:'duplicate',orderForm:{},sizeList:[]}))
    await assert.rejects(migrate({sourceDir:legacy,destinationPath:path.join(dir,'duplicate.sqlite')}))
    assert.equal(fs.existsSync(path.join(dir,'duplicate.sqlite')),false)
    fs.writeFileSync(path.join(legacy,'order.db'),'')
    fs.appendFileSync(path.join(legacy,'setting.db'),'\n'+JSON.stringify({_id:'s2',version:1,baseForm:{}}))
    await assert.rejects(migrate({sourceDir:legacy,destinationPath:path.join(dir,'duplicate-settings.sqlite')}))
    const validLegacySetting=JSON.stringify({_id:'s',version:1,baseForm:{old:1},inactive:99})
    fs.writeFileSync(path.join(legacy,'setting.db'),validLegacySetting)
    const badRow=JSON.stringify({_id:'bad',orderId:'bad-row',orderForm:{},sizeList:[null]})
    fs.writeFileSync(path.join(legacy,'order.db'),badRow)
    await assert.rejects(migrate({sourceDir:legacy,destinationPath:path.join(dir,'bad-row.sqlite')}))
    assert.equal(fs.existsSync(path.join(dir,'bad-row.sqlite')),false)
    assert.equal(fs.readFileSync(path.join(legacy,'order.db'),'utf8'),badRow)
    fs.writeFileSync(path.join(legacy,'order.db'),'')
    for(const invalid of [{baseForm:null},{baseForm:{},typeOptions:[null]}]) {
      const badSetting=JSON.stringify({_id:'s',version:1,...invalid})
      fs.writeFileSync(path.join(legacy,'setting.db'),badSetting)
      await assert.rejects(migrate({sourceDir:legacy,destinationPath:path.join(dir,'bad-setting.sqlite')}))
      assert.equal(fs.existsSync(path.join(dir,'bad-setting.sqlite')),false)
      assert.equal(fs.readFileSync(path.join(legacy,'setting.db'),'utf8'),badSetting)
    }
    console.log('storage: all assertions passed')
  } finally { if(repo)repo.close(); fs.rmSync(dir,{recursive:true,force:true}) }
}
main().catch(e=>{console.error(e);process.exitCode=1})
