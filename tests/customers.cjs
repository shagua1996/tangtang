const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const Database = require('better-sqlite3')
const { Repository, encode } = require('../desktop/database.cjs')
const { migrate } = require('../desktop/migrate.cjs')
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tangtang-customers-'))
const dbPath = path.join(dir, 'customers.sqlite')
let repo
const order = (id, name, call = '') => ({ orderId: id, orderForm: { clientName: name, call }, sizeList: [{ sizeNote: '工艺备注', singlePrice: 10 }], totalPrice: 10 })
const names = (search = '') => repo.listCustomers({ search }).items.map(item => item.name)
function oldDatabase(file, broken = false) {
  const db = new Database(file)
  db.exec('CREATE TABLE orders(order_id TEXT PRIMARY KEY,header TEXT NOT NULL,summary TEXT NOT NULL,item_count INTEGER NOT NULL); PRAGMA user_version=1;')
  const insert = db.prepare('INSERT INTO orders VALUES(?,?,?,0)')
  insert.run('OLD-1', broken ? '{broken' : encode({ ...order('OLD-1', '  老客户  '), sizeList: undefined }), '{}')
  insert.run('OLD-2', encode({ ...order('OLD-2', '老客户'), sizeList: undefined }), '{}')
  db.close()
}
async function main() {
  repo = new Repository(dbPath)
  assert.equal(typeof repo.listCustomers, 'function', '客户查询接口必须存在')
  assert.deepEqual(names(), [])
  repo.createOrder(order('A1', '  客户A  ', '00123'))
  repo.createOrder(order('A2', '客户A'))
  repo.createOrder(order('AB', '客户AB'))
  repo.createOrder(order('EMPTY', '   '))
  repo.createOrder(order('LOWER', 'abc'))
  repo.createOrder(order('UPPER', 'ABC'))
  repo.createOrder(order('SPECIAL', "客户%_'"))
  assert.equal(repo.listCustomers().total, 5)
  assert.equal(names('%')[0], "客户%_'")
  assert.equal(repo.listOrders({ clientName: ' 客户A ' }).total, 2)
  assert.equal(repo.listOrders({ clientName: '客户A', search: '00123' }).total, 1)
  assert.equal(repo.listOrders({ clientName: 'abc' }).total, 1)
  assert.equal(repo.listOrders({ clientName: 'ABC' }).total, 1)
  assert.equal(repo.listOrders().total, 7)
  const before = repo.getOrderHeader('A1'), lines = repo.listOrderItems({ orderId: 'A1' })
  repo.deleteCustomer({ name: '客户A' })
  assert.ok(!names().includes('客户A'))
  assert.deepEqual(repo.getOrderHeader('A1'), before)
  assert.deepEqual(repo.listOrderItems({ orderId: 'A1' }), lines)
  assert.equal(repo.listOrders({ search: '客户A' }).total, 3)
  repo.saveOrderDetail({ orderId: 'A1', detailForm: { receiveName: '甲' }, orderForm: { clientName: '客户A' } })
  assert.ok(!names().includes('客户A'), '仅首尾空格变化不能恢复删除客户')
  repo.close()
  repo = new Repository(dbPath)
  assert.ok(!names().includes('客户A'), '重启不能再次回填被删除客户')
  repo.createOrder(order('A3', '客户A'))
  assert.ok(names().includes('客户A'))
  repo.deleteCustomer({ name: '客户A' })
  repo.saveOrderDetail({ orderId: 'AB', detailForm: {}, orderForm: { clientName: '客户A' } })
  assert.ok(names().includes('客户A'))
  assert.equal(repo.listOrders({ clientName: '客户AB' }).total, 0)
  assert.ok(names().includes('客户AB'), '零订单客户继续保留')
  repo.deleteCustomer({ name: '客户AB' })
  repo.deleteOrders(['A1', 'A2', 'A3', 'AB'])
  assert.ok(names().includes('客户A'), '删除全部订单仍保留客户')
  assert.equal(repo.listOrders({ clientName: '客户A' }).total, 0)
  repo.db.exec("CREATE TRIGGER fail_customer BEFORE INSERT ON customers BEGIN SELECT RAISE(ABORT,'customer failure'); END")
  assert.throws(() => repo.createOrder(order('FAILED', '失败客户')), /customer failure/)
  assert.equal(repo.getOrderHeader('FAILED'), null)
  const original = repo.getOrderHeader('EMPTY')
  assert.throws(() => repo.saveOrderDetail({ orderId: 'EMPTY', detailForm: { receiveName: '失败' }, orderForm: { clientName: '失败客户' } }), /customer failure/)
  assert.deepEqual(repo.getOrderHeader('EMPTY'), original)
  assert.equal(repo.listOrders({ search: '失败客户' }).total, 0)
  repo.db.exec('DROP TRIGGER fail_customer')
  repo.db.transaction(() => {
    for (let i = 0; i < 10000; i++) repo.createOrder(order('PERF-' + String(i).padStart(5, '0'), '性能客户' + String(i).padStart(5, '0')))
    for (let i = 0; i < 101; i++) repo.createOrder(order('PAGE-' + String(i).padStart(3, '0'), '分页客户'))
  })()
  const start = performance.now()
  assert.equal(repo.listCustomers({ search: '性能客户' }).total, 10000)
  assert.equal(repo.listCustomers({ pageSize: 999999 }).items.length, 50)
  assert.equal(repo.listCustomers({ pageSize: 20 }).items.length, 20)
  assert.equal(repo.listCustomers({ search: '性能客户', page: 200 }).items.length, 50)
  assert.equal(repo.listOrders({ clientName: '分页客户', page: 2 }).items.length, 1)
  assert.equal(repo.listOrders({ clientName: '分页客户', page: 2 }).total, 101)
  console.log('customers: 10,000-customer bounded queries took', Math.round(performance.now() - start), 'ms')
  repo.close(); repo = null
  const oldPath = path.join(dir, 'old.sqlite')
  oldDatabase(oldPath)
  repo = new Repository(oldPath)
  assert.equal(repo.db.pragma('user_version', { simple: true }), 2)
  assert.deepEqual(names(), ['老客户'])
  assert.equal(repo.listOrders({ clientName: '老客户' }).total, 2)
  assert.equal(repo.getOrderHeader('OLD-1').orderForm.clientName, '  老客户  ')
  repo.close(); repo = null
  const backupName = fs.readdirSync(dir).find(name => name.startsWith('old.sqlite.before-schema-2-'))
  assert.ok(backupName)
  const backup = new Database(path.join(dir, backupName))
  assert.equal(backup.pragma('user_version', { simple: true }), 1)
  assert.equal(backup.prepare('SELECT count(*) n FROM orders').get().n, 2)
  backup.close()
  const badPath = path.join(dir, 'bad.sqlite')
  oldDatabase(badPath, true)
  assert.throws(() => new Repository(badPath))
  const bad = new Database(badPath)
  assert.equal(bad.pragma('user_version', { simple: true }), 1)
  assert.equal(bad.prepare("SELECT count(*) n FROM sqlite_master WHERE name='customers'").get().n, 0)
  bad.close()
  const legacy = path.join(dir, 'legacy'); fs.mkdirSync(legacy)
  fs.writeFileSync(path.join(legacy, 'order.db'), JSON.stringify({ ...order('LEGACY', '导入客户'), _id: 'legacy' }))
  fs.writeFileSync(path.join(legacy, 'case.db'), '')
  fs.writeFileSync(path.join(legacy, 'setting.db'), '')
  await migrate({ sourceDir: legacy, destinationPath: path.join(dir, 'import.sqlite') })
  repo = new Repository(path.join(dir, 'import.sqlite'))
  assert.deepEqual(names(), ['导入客户'])
  assert.equal(repo.listOrders({ clientName: '导入客户' }).total, 1)
  console.log('customers: memory, deletion, revival, rollback, filtering, migration/backup, import and pagination passed')
}
main().catch(error => { console.error(error); process.exitCode = 1 }).finally(() => { repo?.close(); fs.rmSync(dir, { recursive: true, force: true }) })
