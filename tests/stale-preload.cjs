const { _electron: electron } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs'), path = require('node:path'), os = require('node:os')
const { spawnSync } = require('node:child_process')
const root = path.resolve(__dirname, '..')
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'tangtang-old-preload-'))
const env = { ...process.env, TANGTANG_DATA_DIR: temporary, NODE_PATH: path.join(root, 'node_modules') }
delete env.ELECTRON_RUN_AS_NODE
delete env.TANGTANG_DEV_URL
const seed = spawnSync(require('electron'), ['tests/seed.cjs', temporary], { cwd: root, env: { ...env, ELECTRON_RUN_AS_NODE: '1' }, encoding: 'utf8' })
assert.equal(seed.status, 0, seed.stderr)
fs.cpSync(path.join(root, 'desktop'), path.join(temporary, 'desktop'), { recursive: true })
fs.cpSync(path.join(root, 'dist'), path.join(temporary, 'dist'), { recursive: true })
fs.symlinkSync(path.join(root, 'node_modules'), path.join(temporary, 'node_modules'), 'junction')
const oldPreload = path.join(temporary, 'desktop/preload.cjs')
const entry = path.join(temporary, 'desktop/main.cjs')
const staleMain = process.argv.includes('--old-main')
const removeMethods = source => source.replace(/^\s*'(?:getRecentOrderInputs|rememberOrderInput|deleteRecentOrderInput)',\r?\n/gm, '')
if(staleMain) fs.writeFileSync(entry, removeMethods(fs.readFileSync(entry,'utf8')).replace(', capabilities: { recentOrderInputs: true }',''))
else fs.writeFileSync(oldPreload, removeMethods(fs.readFileSync(oldPreload,'utf8')))
let app
async function main() {
  try {
    app = await electron.launch({ args:[entry], cwd:root, env })
    const page = await app.firstWindow()
    await page.waitForLoadState('domcontentloaded')
    const status = await page.evaluate(() => window.tangtang.getStatus())
    assert.equal(status.ready, true, JSON.stringify(status))
    await page.locator('.calculator-content .input-panel h2').waitFor()
    assert.equal(await page.evaluate(() => typeof window.tangtang.getRecentOrderInputs), staleMain ? 'function' : 'undefined')
    const numbers=page.locator('.calculator-form input[type=number]')
    await numbers.nth(0).fill('900');await numbers.nth(1).fill('2100');await numbers.nth(2).fill('150')
    await page.getByRole('button',{name:'计算并加入明细'}).click()
    await page.getByRole('button',{name:'生成生产单和销售单'}).click()
    await page.getByPlaceholder('输入或选择经销商名称').fill('旧窗口正常输入')
    await page.getByPlaceholder('输入或选择电话').fill('01234567890')
    await page.getByPlaceholder('输入或选择经销商地址').fill('手动输入地址')
    await page.getByRole('dialog').locator('input').nth(4).click()
    await new Promise(resolve=>setTimeout(resolve,400))
    assert.equal(await page.locator('.el-message--error').count(),0,'Old preload must not generate error toasts')
    await page.getByText('最近输入暂不可用，请保存当前订单后重启应用。仍可手动输入。',{exact:true}).waitFor()
    await page.getByRole('dialog').getByRole('button',{name:'创建订单',exact:true}).click()
    await page.locator('.order-view .document-title').waitFor()
    const orders=await page.evaluate(()=>window.tangtang.listOrders({search:'旧窗口正常输入'}))
    assert.equal(orders.total,1)
    assert.equal(orders.items[0].orderForm.call,'01234567890')
    console.log((staleMain ? 'stale-main' : 'stale-preload') + ': old bridge detected, no error toast, manual order creation preserved')
  } finally { await app?.close() }
}
main().catch(error=>{console.error(error);process.exitCode=1})
