const assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { Repository } = require('../desktop/database.cjs')
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tangtang-sale-header-'))
let db = new Repository(path.join(dir, 'test.sqlite'))
try {
  db.createOrder({ orderId: 'SALE-1', orderForm: { no: 'SALE-1', clientName: '原客户', call: '旧电话', orderNote: '保留备注' }, sizeList: [{ doorSize: '820*2060' }], totalPrice: 99 })
  const form = { dealerName: '新经销商', dealerAddress: '新经销商地址', call: '00123456789', clientName: '新客户', clientAddress: '新客户地址', deliveryDate: '2026-12-01', no: '不能改编号', orderNote: '新的整单备注\n第二行' }
  db.saveOrderDetail({ orderId: 'SALE-1', detailForm: { yingPay: '99' }, orderForm: form })
  const saved = db.getOrderHeader('SALE-1')
  assert.equal(saved.orderForm.clientName, '新客户')
  assert.equal(saved.orderForm.no, 'SALE-1')
  assert.equal(saved.orderForm.orderNote, '新的整单备注\n第二行')
  assert.equal(db.listOrders({ search: '保留备注' }).total, 0)
  assert.equal(db.listOrders({ search: '新的整单备注' }).total, 1)
  assert.equal(saved.totalPrice, 99)
  assert.deepEqual(db.listOrderItems({ orderId: 'SALE-1' }).items, [{ doorSize: '820*2060' }])
  assert.equal(db.listOrders({ search: '原客户' }).total, 0)
  assert.equal(db.listOrders({ search: '旧电话' }).total, 0)
  assert.equal(db.listOrders({ search: '00123456789' }).items[0].orderForm.clientName, '新客户')
  db.db.exec("CREATE TRIGGER fail_search BEFORE INSERT ON order_search BEGIN SELECT RAISE(ABORT, 'search failure'); END")
  assert.throws(() => db.saveOrderDetail({ orderId: 'SALE-1', orderForm: { clientName: '失败客户' }, detailForm: { yingPay: '1' } }), /search failure/)
  assert.deepEqual(db.getOrderHeader('SALE-1'), saved)
  assert.equal(db.listOrders({ search: '新客户' }).total, 1)
  assert.equal(db.listOrders({ search: '失败客户' }).total, 0)
  db.db.exec('DROP TRIGGER fail_search')
  // Old callers can still save only the seven footer fields.
  db.saveOrderDetail({ orderId: 'SALE-1', detailForm: { receiveName: '收货人' } })
  assert.deepEqual(db.getOrderHeader('SALE-1').orderForm, saved.orderForm)
  db.saveOrderDetail({ orderId: 'SALE-1', detailForm: {}, orderForm: { deliveryDate: '', call: '' } })
  db.close()
  db = new Repository(path.join(dir, 'test.sqlite'))
  assert.equal(db.getOrderHeader('SALE-1').orderForm.deliveryDate, '')
  assert.equal(db.getOrderHeader('SALE-1').orderForm.call, '')
  assert.equal(db.getOrderHeader('SALE-1').orderForm.clientName, '新客户')
  console.log('sale-header-storage: six fields, atomic summary/search rollback, immutable number/formulas, old callers and restart passed')
} finally { db.close(); fs.rmSync(dir, { recursive: true, force: true }) }
